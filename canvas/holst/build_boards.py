import textwrap
from pathlib import Path

OUT = Path(__file__).resolve().parent
W = 1440
PAD = 48
BG = "#101E19"
PANEL = "#192D25"
INK = "#F1F6E8"
MUTED = "#ACC0B0"
ACCENT = "#BCED91"
LINE = "#3E5549"
WARM = "#F2CB92"


def esc(value):
    return (
        str(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def wrap(text, width_px, size=16):
    chars = max(12, int(width_px / (size * 0.52)))
    return textwrap.wrap(text, chars) or [""]


class Board:
    def __init__(self, kicker, title):
        self.parts = []
        self.y = 36
        self.kicker(kicker)
        self.title(title)

    def kicker(self, text):
        self.parts.append(
            f'<text x="{PAD}" y="{self.y}" fill="{MUTED}" font-family="Consolas, monospace" font-size="13">{esc(text)}</text>'
        )
        self.y += 28

    def title(self, text):
        self.parts.append(
            f'<text x="{PAD}" y="{self.y}" fill="{INK}" font-family="Segoe UI, Arial, sans-serif" font-size="36" font-weight="700">{esc(text)}</text>'
        )
        self.y += 28

    def paragraph(self, text, width=None, fill=MUTED, size=16):
        width = width or (W - PAD * 2)
        self.y += 8
        for line in wrap(text, width, size):
            self.y += size + 8
            self.parts.append(
                f'<text x="{PAD}" y="{self.y}" fill="{fill}" font-family="Segoe UI, Arial, sans-serif" font-size="{size}">{esc(line)}</text>'
            )
        self.y += 10

    def callout(self, heading, text):
        lines = wrap(text, W - PAD * 2 - 36, 16)
        height = 36 + len(lines) * 24 + 16
        top = self.y + 8
        self.parts.append(
            f'<rect x="{PAD}" y="{top}" width="{W - PAD * 2}" height="{height}" fill="{PANEL}" stroke="{LINE}"/>'
        )
        self.parts.append(
            f'<rect x="{PAD}" y="{top}" width="4" height="{height}" fill="{WARM}"/>'
        )
        self.parts.append(
            f'<text x="{PAD + 20}" y="{top + 28}" fill="{WARM}" font-family="Segoe UI, Arial, sans-serif" font-size="16" font-weight="700">{esc(heading)}</text>'
        )
        yy = top + 28
        for line in lines:
            yy += 24
            self.parts.append(
                f'<text x="{PAD + 20}" y="{yy}" fill="{INK}" font-family="Segoe UI, Arial, sans-serif" font-size="16">{esc(line)}</text>'
            )
        self.y = top + height + 12

    def table(self, headers, rows, widths):
        self.y += 8
        head_h = 36
        self.parts.append(
            f'<rect x="{PAD}" y="{self.y}" width="{sum(widths)}" height="{head_h}" fill="#244031"/>'
        )
        x = PAD
        for header, width in zip(headers, widths):
            self.parts.append(
                f'<text x="{x + 10}" y="{self.y + 24}" fill="{ACCENT}" font-family="Consolas, monospace" font-size="13">{esc(header)}</text>'
            )
            x += width
        self.y += head_h
        for index, row in enumerate(rows):
            wrapped = [wrap(cell, width - 20, 15) for cell, width in zip(row, widths)]
            lines = max(len(item) for item in wrapped)
            row_h = 16 + lines * 22
            fill = PANEL if index % 2 == 0 else "#14241C"
            self.parts.append(
                f'<rect x="{PAD}" y="{self.y}" width="{sum(widths)}" height="{row_h}" fill="{fill}" stroke="{LINE}"/>'
            )
            x = PAD
            for cell_lines, width in zip(wrapped, widths):
                yy = self.y + 22
                for line in cell_lines:
                    self.parts.append(
                        f'<text x="{x + 10}" y="{yy}" fill="{INK}" font-family="Segoe UI, Arial, sans-serif" font-size="15">{esc(line)}</text>'
                    )
                    yy += 22
                x += width
            self.y += row_h
        self.y += 12

    def era(self):
        self.y += 12
        top = self.y
        scale = (W - PAD * 2 - 160) / 33
        def x_year(year):
            return PAD + 150 + (year - 1992) * scale
        self.parts.append(
            f'<text x="{PAD}" y="{top + 16}" fill="{MUTED}" font-family="Segoe UI, Arial, sans-serif" font-size="14">АМЕ-60, 15 минут</text>'
        )
        self.parts.append(
            f'<rect x="{x_year(1992):.1f}" y="{top + 28}" width="{x_year(1999) - x_year(1992):.1f}" height="18" fill="{ACCENT}"/>'
        )
        self.parts.append(
            f'<rect x="{x_year(1999):.1f}" y="{top + 28}" width="{x_year(2003.62) - x_year(1999):.1f}" height="18" fill="#24382E" stroke="{WARM}"/>'
        )
        self.parts.append(
            f'<rect x="{x_year(2003.62):.1f}" y="{top + 28}" width="{x_year(2021) - x_year(2003.62):.1f}" height="18" fill="{ACCENT}"/>'
        )
        self.parts.append(
            f'<text x="{PAD}" y="{top + 78}" fill="{MUTED}" font-family="Segoe UI, Arial, sans-serif" font-size="14">Сокол М1, Кр1 и Кр2 отдельно</text>'
        )
        self.parts.append(
            f'<rect x="{x_year(2022):.1f}" y="{top + 90}" width="{x_year(2025) - x_year(2022):.1f}" height="18" fill="{INK}"/>'
        )
        self.parts.append(
            f'<text x="{x_year(1999):.1f}" y="{top + 64}" fill="{WARM}" font-family="Segoe UI, Arial, sans-serif" font-size="13">нет данных 4 янв 1999 - 17 авг 2003</text>'
        )
        self.y = top + 130

    def save(self, name):
        height = self.y + 36
        body = "\n".join(self.parts)
        svg = (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{height}" viewBox="0 0 {W} {height}">'
            f'<rect width="{W}" height="{height}" fill="{BG}"/>'
            f"{body}</svg>"
        )
        (OUT / name).write_text(svg, encoding="utf-8")
        print(name, height)


